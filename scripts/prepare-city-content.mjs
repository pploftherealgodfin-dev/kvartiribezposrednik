import { readFile, writeFile, readdir } from 'node:fs/promises';

// Reproducible frontend derivatives of the reviewed, public catalogue. No API or DB access.
export async function prepareCityContent() {
  const catalog = JSON.parse(await readFile('public/data/national-catalog.json', 'utf8'));
  const { cities, universities, neighborhoods } = catalog;
  if (cities.length !== 257 || new Set(cities.map(city => city.slug)).size !== 257) throw new Error('Unexpected city catalogue');
  const known = new Set(cities.map(city => city.slug));
  for (const item of [...universities, ...neighborhoods]) if (!known.has(item.citySlug)) throw new Error(`Unknown city: ${item.citySlug}`);
  const distance = (a, b) => {
    const rad = degrees => degrees * Math.PI / 180;
    const v = Math.sin(rad(b.lat - a.lat) / 2) ** 2 + Math.cos(rad(a.lat)) * Math.cos(rad(b.lat)) * Math.sin(rad(b.lng - a.lng) / 2) ** 2;
    return 6371 * 2 * Math.atan2(Math.sqrt(v), Math.sqrt(1 - v));
  };
  const local = {}, summary = {};
  for (const city of cities) {
    const areas = neighborhoods.filter(item => item.citySlug === city.slug).map(({ slug, name, sourceRef, associationMethod }) => ({ slug, name, sourceRef, associationMethod }));
    const schools = universities.filter(item => item.citySlug === city.slug).map(({ slug, name, sourceUrl, kind }) => ({ slug, name, sourceUrl, kind }));
    const positioned = city.lat != null && city.lng != null;
    const nearby = cities.filter(item => item.slug !== city.slug && (positioned ? item.lat != null && item.lng != null : item.region === city.region))
      .map(item => ({ slug: item.slug, ...(positioned ? { km: Math.round(distance(city, item) * 10) / 10 } : {}) }))
      .sort((a, b) => positioned ? a.km - b.km : a.slug.localeCompare(b.slug)).slice(0, 6);
    local[city.slug] = { ekatte: city.ekatte, lat: city.lat, lng: city.lng, coordinateSource: city.coordinateSource, areas, universities: schools, nearby };
    summary[city.slug] = { areas: areas.filter(item => item.associationMethod !== 'nearest_town_approximate').length, universities: schools.length, nearby: cities.find(item => item.slug === nearby[0]?.slug)?.name };
  }
  // Copy only literal metadata; full article text stays in lazy page chunks.
  const literal = (source, field) => {
    const match = source.match(new RegExp(`^  ${field}:\\s*('(?:\\\\.|[^'\\\\])*'|"(?:\\\\.|[^"\\\\])*")`, 'm'));
    if (!match) return undefined;
    return match[1][0] === '"' ? JSON.parse(match[1]) : match[1].slice(1, -1).replace(/\\'/g, "'").replace(/\\n/g, '\n').replace(/\\\\/g, '\\');
  };
  const photos = {};
  for (const file of (await readdir('src/pages/cities/data')).filter(file => file.endsWith('.ts') && !['index.ts', 'types.ts', 'localCatalog.ts', 'photos.ts'].includes(file)).sort()) {
    const source = await readFile(`src/pages/cities/data/${file}`, 'utf8');
    const slug = literal(source, 'slug'), heroImage = literal(source, 'heroImage');
    if (slug && heroImage) photos[slug] = { heroImage, heroImageCredit: literal(source, 'heroImageCredit') };
  }
  if (Object.keys(photos).length !== 12) throw new Error('The twelve Readdy city photos must be preserved');
  const editorial = [];
  for (const file of (await readdir('src/pages/guides/data')).filter(file => !['index.ts', 'types.ts'].includes(file) && file.endsWith('.ts')).sort()) {
    const source = await readFile(`src/pages/guides/data/${file}`, 'utf8');
    const slug = literal(source, 'slug'), title = literal(source, 'title'), description = literal(source, 'excerpt');
    if (!slug || !title || !description) throw new Error(`Missing literal guide metadata in ${file}`);
    editorial.push({ path: `/saveti/${slug}`, title, description, ogImage: literal(source, 'heroImage'), ogType: 'article' });
  }
  const info = await readFile('src/pages/info/content.ts', 'utf8');
  for (const match of info.matchAll(/^  '(\/[^']+)': \{\n    title: ('[^']+'),\n    intro: ('[^']+'),/gm)) editorial.push({ path: match[1], title: match[2].slice(1, -1), description: match[3].slice(1, -1) });
  if (editorial.length !== 8) throw new Error('Expected five guides and three information pages');
  const header = '// Generated by scripts/prepare-city-content.mjs. Edit the source catalogue or editorial files.\n';
  await writeFile('src/pages/cities/data/localCatalog.ts', `${header}import type { CityLocalProfile } from './types';\nexport const catalogSnapshot = ${JSON.stringify(catalog.metadata.snapshot)};\nexport const localCatalog: Record<string, CityLocalProfile> = ${JSON.stringify(local)};\n`);
  await writeFile('src/pages/cities/data/photos.ts', `${header}export const cityPhotos: Record<string, { heroImage: string; heroImageCredit: string }> = ${JSON.stringify(photos, null, 2)};\n`);
  await writeFile('src/lib/citySeoSummary.ts', `${header}export const citySeoSummary: Record<string, { areas: number; universities: number; nearby: string }> = ${JSON.stringify(summary)};\n`);
  await writeFile('src/lib/editorialSeoIndex.ts', `${header}export const editorialSeoIndex = ${JSON.stringify(editorial, null, 2)};\n`);
}
if (process.argv[1]?.endsWith('prepare-city-content.mjs')) await prepareCityContent();
